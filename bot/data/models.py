class LearningEvent(Base):
    """Labeled training data for the adaptive learning system."""

    __tablename__ = "learning_events"
    __table_args__ = (Index("ix_learning_strategy_ts", "strategy_name", "recorded_at"),)

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    trade_id: Mapped[Optional[int]] = mapped_column(Integer, ForeignKey("trades.id"), nullable=True)
    symbol: Mapped[str] = mapped_column(String(20), nullable=False)
    strategy_name: Mapped[str] = mapped_column(String(50), nullable=False)
    feature_vector: Mapped[Dict[str, Any]] = mapped_column(JSON, nullable=False)
    outcome: Mapped[int] = mapped_column(Integer, nullable=False)  # 1=win, 0=loss
    predicted_outcome: Mapped[Optional[float]] = mapped_column(Float, nullable=True)
    model_version: Mapped[int] = mapped_column(Integer, default=1)
    recorded_at: Mapped[datetime] = mapped_column(DateTime, server_default=func.now())
